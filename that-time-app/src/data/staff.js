// ── Helpers ────────────────────────────────────────────────────────────────

export const isInstructor = (s) => Boolean(s?.systemRoles?.includes('Instructor'));
export const isActive     = (s) => Boolean(s?.active);
export const isBookable   = (s) => Boolean(s?.active && s?.bookable && s?.profile?.visibleOnProfile);

// All members with Instructor role — used for the lead-instructor list in
// the class wizard.
export const instructorsList = (members = staff) => members.filter((s) => isActive(s) && isInstructor(s));

// All active members — used for the supporting-staff picker.
export const activeStaffList = (members = staff) => members.filter(isActive);

// Lookup by id with safe fallback.
export const staffById = (id, members = staff) => members.find((s) => s.id === id);

// Initials for the avatar fallback (no photos in mock data).
export const initialsFor = (s) =>
  (s?.name || '')
    .split(' ')
    .map((p) => p[0])
    .filter(Boolean)
    .slice(0, 2)
    .join('')
    .toUpperCase();

export const emptyWeeklySchedule = () => weekdaySchedule('09:00', '17:00', ['Mon', 'Tue', 'Wed', 'Thu', 'Fri']);
